#!/usr/bin/env bash
# Maintain Docker bridge -> VPN XFRM SNAT rules in the host network namespace.
set -euo pipefail

readonly CHAIN=STRONGSWAN_SNAT
readonly -a IPTABLES=(iptables -w 5)

log() { printf '[snat] %s\n' "$*" >&2; }

# Get the source address the host would use to reach the VPN IPsec peer.
# `ip route get` does not send packets.
detect_source_ip() {
  if [[ -n "${VPN_SNAT_SOURCE_IP:-}" ]]; then
    printf '%s\n' "$VPN_SNAT_SOURCE_IP"
    return
  fi

  local peer="${VPN_OCI_TUN_1_IP:-1.1.1.1}"
  local route source_ip
  route="$(ip -4 route get "$peer")" || return 1
  source_ip="$(awk '{for (i=1; i<=NF; i++) if ($i=="src") {print $(i+1); exit}}' <<< "$route")"
  if [[ -z "$source_ip" ]]; then
    log "Could not determine host IPv4 source address for $peer"
    return 1
  fi
  printf '%s\n' "$source_ip"
}

# Accept a comma-, semicolon-, or whitespace-separated set of TCP destination
# ports. One POSTROUTING jump is used per port, avoiding multiport's 15-port cap.
# Normalize leading zeroes and discard duplicate entries.
detect_ports() {
  local token port
  local input="${VPN_SNAT_PORTS:-1522}"
  local -a result=()

  while IFS= read -r token; do
    [[ -n "$token" ]] || continue
    if ! [[ "$token" =~ ^[0-9]{1,5}$ ]]; then
      log "Invalid TCP port '$token' in VPN_SNAT_PORTS (expected 1-65535)"
      return 1
    fi
    port=$((10#$token))
    if (( port < 1 || port > 65535 )); then
      log "Invalid TCP port '$token' in VPN_SNAT_PORTS (expected 1-65535)"
      return 1
    fi
    result+=("$port")
  done < <(printf '%s\n' "$input" | tr ',;' ' ' | tr '[:space:]' '\n')

  if (( ${#result[@]} == 0 )); then
    log 'VPN_SNAT_PORTS must contain at least one TCP destination port'
    return 1
  fi
  printf '%s\n' "${result[@]}" | sort -n -u
}

# Works without Docker's socket: the host namespace exposes the kernel's
# connected routes for standard Docker bridge interfaces (docker0 / br-*).
# Custom bridge interface names, macvlan, ipvlan and remote networks can be
# supplied through VPN_SNAT_NETWORKS or VPN_SNAT_EXTRA_NETWORKS.
detect_networks() {
  if [[ "${VPN_SNAT_NETWORKS:-auto}" == auto ]]; then
    ip -4 route show scope link | awk '
      {
        dev=""
        for (i=1; i<=NF; i++) if ($i=="dev") dev=$(i+1)
        if ((dev=="docker0" || dev ~ /^br-/) && $1 ~ /^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+\/[0-9]+$/)
          print $1
      }'
  else
    printf '%s\n' "$VPN_SNAT_NETWORKS" | tr ',;' ' ' | tr '[:space:]' '\n' | sed '/^$/d'
  fi

  if [[ -n "${VPN_SNAT_EXTRA_NETWORKS:-}" ]]; then
    printf '%s\n' "$VPN_SNAT_EXTRA_NETWORKS" | tr ',;' ' ' | tr '[:space:]' '\n' | sed '/^$/d'
  fi
}

# First line: SNAT source IP; second line: normalized CSV ports;
# remaining lines: sorted Docker CIDRs. Include ports so watch detects changes.
snapshot() {
  local source_ip ports
  source_ip="$(detect_source_ip)" || return 1
  ports="$(detect_ports | paste -sd, -)" || return 1
  printf '%s\n%s\n' "$source_ip" "$ports"
  detect_networks | sort -u
}

# Remove all jumps to our dedicated chain, including old single-port rules
# from previous versions or stale port entries after a configuration change.
# Only the known, unquoted rule form generated by this script is considered.
remove_owned_jumps() {
  local rule
  local -a parts
  while IFS= read -r rule; do
    [[ "$rule" == '-A POSTROUTING '* && "$rule" == *" -j $CHAIN" ]] || continue
    read -r -a parts <<< "$rule"
    "${IPTABLES[@]}" -t nat -D POSTROUTING "${parts[@]:2}" || return 1
  done < <("${IPTABLES[@]}" -t nat -S POSTROUTING)
}

# Keep configured port jumps at the top of POSTROUTING, ahead of Docker's
# catch-all MASQUERADE rules. Reconcile if other processes move/add rules.
ensure_jumps_first() {
  local -a ports=("$@") existing=()
  local rule port i own_count=0 valid=1
  mapfile -t existing < <("${IPTABLES[@]}" -t nat -S POSTROUTING | awk '$1=="-A" && $2=="POSTROUTING"')

  for rule in "${existing[@]}"; do
    if [[ "$rule" == *" -j $CHAIN" ]]; then
      ((own_count += 1))
    fi
  done
  if (( own_count != ${#ports[@]} )); then
    valid=0
  else
    for i in "${!ports[@]}"; do
      port="${ports[$i]}"
      rule="${existing[$i]:-}"
      if [[ "$rule" != *' -o xfrm-oci+ '* || "$rule" != *" --dport $port -j $CHAIN" ]]; then
        valid=0
        break
      fi
    done
  fi
  if (( valid == 1 )); then
    return 0
  fi

  remove_owned_jumps || return 1
  for ((i=${#ports[@]} - 1; i>=0; i--)); do
    "${IPTABLES[@]}" -t nat -I POSTROUTING 1 -o xfrm-oci+ -p tcp --dport "${ports[$i]}" -j "$CHAIN" || return 1
  done
}

apply_snapshot() {
  local desired="$1" source_ip port_csv net
  local -a addresses ports
  mapfile -t addresses <<< "$desired"
  source_ip="${addresses[0]:-}"
  port_csv="${addresses[1]:-}"
  if [[ -z "$source_ip" || -z "$port_csv" ]]; then
    log 'No SNAT source IP or TCP ports, skipping changes'
    return 1
  fi
  IFS=',' read -r -a ports <<< "$port_csv"

  "${IPTABLES[@]}" -t nat -N "$CHAIN" 2>/dev/null || true
  "${IPTABLES[@]}" -t nat -F "$CHAIN" || return 1
  for net in "${addresses[@]:2}"; do
    [[ -n "$net" ]] || continue
    "${IPTABLES[@]}" -t nat -A "$CHAIN" -s "$net" -j SNAT --to-source "$source_ip" || return 1
  done
  ensure_jumps_first "${ports[@]}" || return 1
  log "SNAT via xfrm-oci+ TCP ports [$port_csv] to $source_ip for $((${#addresses[@]} - 2)) Docker subnet(s)"
}

cleanup() {
  remove_owned_jumps || true
  "${IPTABLES[@]}" -t nat -F "$CHAIN" 2>/dev/null || true
  "${IPTABLES[@]}" -t nat -X "$CHAIN" 2>/dev/null || true
  log 'Removed owned SNAT rules'
}

watch() {
  local interval="${VPN_SNAT_REFRESH_SECONDS:-15}"
  if ! [[ "$interval" =~ ^[0-9]+$ ]] || (( interval < 1 )); then
    log 'VPN_SNAT_REFRESH_SECONDS must be a positive integer'
    return 1
  fi

  local previous='' current port_csv
  local -a ports
  while :; do
    if current="$(snapshot)"; then
      if [[ "$current" != "$previous" ]] || ! "${IPTABLES[@]}" -t nat -L "$CHAIN" -n >/dev/null 2>&1; then
        if apply_snapshot "$current"; then
          previous="$current"
        else
          log 'SNAT update failed; retrying on next refresh'
        fi
      else
        port_csv="$(sed -n '2p' <<< "$current")"
        IFS=',' read -r -a ports <<< "$port_csv"
        ensure_jumps_first "${ports[@]}" || log 'Could not ensure POSTROUTING hooks; retrying'
      fi
    else
      log 'Could not discover SNAT parameters; retrying'
    fi
    sleep "$interval"
  done
}

case "${1:-watch}" in
  source-ip) detect_source_ip ;;
  show)
    source_ip="$(detect_source_ip)" || exit 1
    ports="$(detect_ports | paste -sd, -)" || exit 1
    printf 'Source IP: %s\n' "$source_ip"
    printf 'TCP destination ports: %s\n' "$ports"
    printf 'Docker CIDRs:\n'
    detect_networks | sort -u | sed 's/^/  /'
    ;;
  sync) apply_snapshot "$(snapshot)" ;;
  watch) watch ;;
  cleanup) cleanup ;;
  *) log 'Usage: snat.sh [show|source-ip|sync|watch|cleanup]'; exit 2 ;;
esac
